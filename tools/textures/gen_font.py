EXTRA_CHARS = [
    "\u00b7", "\u2014", "\u2013", "\u00b0", "\u2019", "\u2018",
    "\u201c", "\u201d", "\u2022", "\u00d7", "\u2026",
]


def draw_stroke(draw, pts, ox, oy, scale_x, scale_y, width):
    if len(pts) < 2:
        return
    r = width * 0.5
    coords = [(ox + p[0] * scale_x, oy + p[1] * scale_y) for p in pts]
    draw.line(coords, fill=(255, 255, 255, 255), width=int(round(width)), joint="curve")
    for cx, cy in coords:
        draw.ellipse((cx - r, cy - r, cx + r, cy + r), fill=(255, 255, 255, 255))


def main():
    out_dir = os.path.join(sys.argv[-1], "ui")
    os.makedirs(out_dir, exist_ok=True)

    # Supersample 2x for silky anti-aliased ink strokes!
    ss = 2
    img = Image.new("RGBA", (ATLAS_W * ss, ATLAS_H * ss), (255, 255, 255, 0))
    draw = ImageDraw.Draw(img)

    chars = [chr(c) for c in range(32, 127)] + EXTRA_CHARS
    assert len(chars) <= COLS * ROWS, f"Too many glyphs ({len(chars)}) for {COLS}x{ROWS} atlas"
    entries = []
    for idx, ch in enumerate(chars):
        col = idx % COLS
        row = idx // COLS
        cx = col * CELL
        cy = row * CELL
        strokes = GLYPHS.get(ch, [])
        pad = 6
        gx = (cx + pad) * ss
        gy = (cy + 5) * ss
        gw = (CELL - pad * 2 - 4) * ss
        gh = 26 * ss
        stroke_w = 3.2 * ss
        for poly in strokes:
            draw_stroke(draw, poly, gx, gy, gw, gh, stroke_w)

        # Measure exact horizontal ink bounds in cell coordinates for tight, even kerning.
        if ch == " " or not strokes:
            xoff = 0
            xadv = 11
        else:
            xs = [p[0] for poly in strokes for p in poly]
            min_x = min(xs)
            max_x = max(xs)
            gw_1x = CELL - pad * 2 - 4
            left_px = pad + min_x * gw_1x - 1.6
            right_px = pad + max_x * gw_1x + 1.6
            ink_w = max(right_px - left_px, 4.0)
            side_bearing = 2.0
            if ch in "\u2014\u2013":
                side_bearing = 3.0
            elif ch in "\u00b7\u2022":
                side_bearing = 4.0
            xoff = int(round(side_bearing - left_px))
            xadv = int(round(ink_w + side_bearing * 2.0))
            xadv = max(xadv, 8)
        entries.append((ord(ch), cx, cy, CELL, CELL, xoff, 0, xadv))

    final_img = img.resize((ATLAS_W, ATLAS_H), Image.LANCZOS)
    png_path = os.path.join(out_dir, "scoundrel_font.png")
    fnt_path = os.path.join(out_dir, "scoundrel_font.fnt")
    final_img.save(png_path, optimize=True)

    lines = [
        'info face="ScoundrelInk" size=32 bold=1 italic=0 charset="" unicode=1 stretchH=100 smooth=1 aa=1 padding=0,0,0,0 spacing=1,1',
        f"common lineHeight={LINE_H} base={BASE_Y} scaleW={ATLAS_W} scaleH={ATLAS_H} pages=1 packed=0",
        'page id=0 file="scoundrel_font.png"',
        f"chars count={len(entries)}",
    ]
    for code, x, y, w, h, xo, yo, xa in entries:
        lines.append(f"char id={code} x={x} y={y} width={w} height={h} xoffset={xo} yoffset={yo} xadvance={xa} page=0 chnl=15")
    with open(fnt_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  wrote {png_path} and {fnt_path} ({len(entries)} glyphs)")


